// 這是 HAL 庫專屬的外部中斷回呼函數
void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin)
{
  if (GPIO_Pin == GPIO_PIN_0) // 確認是 PA0 觸發的中斷
  {
    // 使用 static 變數記錄上一次觸發的時間
    static uint32_t last_irq_time = 0;
    uint32_t current_time = HAL_GetTick(); // 取得現在的時間 (單位：毫秒)
    
    // 軟體濾波：兩次脈衝間隔必須大於等於 2 毫秒 (最高支援到 15000 RPM 才有效)
    // 這樣可以完美過濾掉 25kHz (間隔 0.04 毫秒) 的串擾雜訊
    if (current_time - last_irq_time >= 2) 
    {
      tach_pulse_count++; // 脈衝數 +1
      last_irq_time = current_time; // 更新最後觸發時間
    }
  }
}
