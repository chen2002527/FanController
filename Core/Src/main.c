/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_TIM1_Init();
  MX_USB_DEVICE_Init();
  /* USER CODE BEGIN 2 */

  // 啟動 TIM1 的 Channel 1 PWM 輸出
  HAL_TIM_PWM_Start(&htim1, TIM_CHANNEL_1);
  
  // 設定 PWM 的佔空比 (Duty Cycle)
  // 因為我們的 ARR 設定為 319，所以轉速的範圍是 0 (停止) 到 319 (全速)
  // 我們先設定 160，大約是 50% 的轉速
  __HAL_TIM_SET_COMPARE(&htim1, TIM_CHANNEL_1, 10);

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    uint32_t now = HAL_GetTick();

    // 1. 處理 PC 傳來的 USB 指令 (非阻塞)
    if (usb_cmd_ready)
    {
      usb_cmd_ready = 0;
      if (strncmp(usb_rx_buffer, "PWM:", 4) == 0)
      {
        int val = atoi(&usb_rx_buffer[4]);
        if (val >= 0 && val <= 319)
        {
          current_pwm = (uint16_t)val;
          __HAL_TIM_SET_COMPARE(&htim1, TIM_CHANNEL_1, current_pwm);
        }
      }
    }

    // 2. 每 1000ms 精準結算一次 RPM 並透過 USB 回傳給 PC
    if (now - last_rpm_tick >= 1000)
    {
      // 暫時關閉中斷或直接讀取並清零，避免 Race Condition
      uint32_t pulses = tach_pulse_count;
      tach_pulse_count = 0;
      last_rpm_tick = now;

      fan_rpm = (pulses / 2) * 60;

      // 組裝字串並透過 USB CDC 發送給 PC
      char tx_buf[64];
      int len = snprintf(tx_buf, sizeof(tx_buf), "RPM:%lu,PWM:%u\r\n", fan_rpm, current_pwm);
      CDC_Transmit_FS((uint8_t*)tx_buf, len);
    }

    // 3. 每 500ms 閃爍一次狀態燈 (取代原本會卡死迴圈的 HAL_Delay)
    if (now - last_led_tick >= 500)
    {
      last_led_tick = now;
      HAL_GPIO_TogglePin(GPIOC, GPIO_PIN_13);
    }
    /* USER CODE END WHILE */
  }
}

